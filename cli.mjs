function checkRuleFrontmatter(content) {
  const fields = parseFrontmatter(content);
  if (!fields?.trigger || !['always_on', 'model_decision', 'glob', 'manual'].includes(fields.trigger)) return false;
  if (fields.trigger === 'model_decision' && !fields.description) return false;
  if (fields.trigger === 'glob' && !fields.globs && !fields.glob) return false;
  return true;
}

export function diagnoseProject(projectDir = process.cwd(), requestedMode = 'auto') {
  if (!['auto', 'agent', 'skill', 'both'].includes(requestedMode)) {
    throw new Error(`โหมด doctor ไม่ถูกต้อง: ${requestedMode}`);
  }
  const checks = [];
  const checkFile = (relativePath, predicate = () => true, { optional = false } = {}) => {
    const path = join(projectDir, relativePath);
    const exists = existsSync(path);
    let valid = exists ? predicate(readFileSync(path, 'utf8')) : optional;
    checks.push({ path: relativePath, ok: Boolean(valid), optional });
  };

  checkFile('AGENTS.md');
  checkFile(join('.agents', 'project', 'project-context.md'));
  checkFile(join('.agents', 'project', 'architecture.md'));
  checkFile(join('.agents', 'project', 'technical-debt.md'));
  checkFile(PROJECT_CONFIG, (content) => {
    try {
      const config = parseProjectConfig(content);
      return ['ask', 'auto', 'off'].includes(config?.git?.commitPolicy);
    } catch { return false; }
  }, { optional: true });

  let manifest = null;
  try { manifest = readProjectManifest(projectDir); } catch { /* reported below as an optional integrity check */ }
  const agentFile = join('.agents', 'agents', 'engineering-team', 'agent.md');
  const skillsRoot = join(projectDir, '.agents', 'skills');
  const hasAgent = existsSync(join(projectDir, agentFile)) || manifest?.modes?.includes('agent');
  const skillFiles = listMarkdownFiles(skillsRoot).filter((path) => path.split(/[\\/]/).at(-1) === 'SKILL.md');
  const hasSkill = skillFiles.length > 0 || manifest?.modes?.includes('skill');
  const modes = requestedMode === 'auto'
    ? [...new Set([...(manifest?.modes ?? []), ...(hasAgent ? ['agent'] : []), ...(hasSkill ? ['skill'] : [])])]
    : requestedMode === 'both' ? ['agent', 'skill'] : [requestedMode];

  if (modes.length === 0) checks.push({ path: '.agents (Agent หรือ Skill)', ok: false, optional: false });
  if (modes.includes('agent')) {
    checkFile(agentFile, (content) => validFrontmatter(content, 'engineering-team'));
    checkFile(join('.agents', 'rules', '00-engineering-team.md'), checkRuleFrontmatter);
    const agentsRoot = join(projectDir, '.agents', 'agents');
    for (const agentPath of listMarkdownFiles(agentsRoot).filter((path) => path.split(/[\\/]/).at(-1) === 'agent.md')) {
      const rel = relative(projectDir, agentPath);
      if (rel === agentFile) continue;
      checkFile(rel, (content) => validFrontmatter(content));
    }
  }
  if (modes.includes('skill')) {
    if (skillFiles.length === 0) checks.push({ path: join('.agents', 'skills', '**', 'SKILL.md'), ok: false, optional: false });
    for (const skillPath of skillFiles) {
      checkFile(relative(projectDir, skillPath), checkSkillFrontmatter);
    }
  }
  if (existsSync(join(projectDir, '.agent-skill-manager.json'))) {
    checks.push({ path: '.agent-skill-manager.json', ok: manifest !== null, optional: false });
  }
  return checks;
}

export function runDoctor(projectDir = process.cwd(), { mode = 'auto', json = false } = {}) {
  const checks = diagnoseProject(projectDir, mode);
  const failed = checks.filter((check) => !check.ok);
  if (json) {
    console.log(JSON.stringify({ ok: failed.length === 0, mode, checks }, null, 2));
  } else {
    for (const check of checks) console.log(`${check.ok ? 'ผ่าน' : 'ไม่ผ่าน'}: ${check.path}`);
    if (failed.length > 0) console.log(`\nตรวจพบ ${failed.length} รายการที่ต้องแก้ไข`);
    else console.log(`\nโครงสร้าง Agent/Skill พร้อมใช้งาน (${checks.length} รายการ)`);
  }
  if (failed.length > 0) process.exitCode = 1;
  return failed.length === 0;
}

export function writeCompiledRules(rules, outputDir = process.cwd(), mode = 'skill', options = {}) {
  const plan = planCompiledRules(rules, outputDir, mode, {
    conflictPolicy: options.conflictPolicy ?? 'error',
    commitPolicy: options.commitPolicy ?? null,
  });
  if (plan.entries.some((entry) => entry.action === 'conflict')) {
    throw new Error('ไฟล์ชนกัน ต้องเลือกนโยบายก่อนเขียน');
  }
  applyWritePlan(plan, { dryRun: options.dryRun ?? false });
  return plan.entries.map((entry) => join(outputDir, entry.relativePath));
}

function formatChoice(rule) {
  const key = ruleKey(rule);
  const name = FRIENDLY_NAMES[key] ?? rule.title;
  const category = CATEGORY_LABELS[rule.category] ?? rule.category;
  return `${name} — ${category}`;
}

function actionLabel(action) {
  return ({
    create: 'สร้างใหม่',
    update: 'อัปเดตไฟล์ที่จัดการได้',
    overwrite: 'เขียนทับ (สำรองไฟล์เดิม)',
    unchanged: 'เหมือนเดิม',
    preserve: 'เก็บไฟล์เดิมตามนโยบาย',
    keep: 'เก็บไฟล์เดิม (ข้ามรายการนี้)',
    conflict: 'พบไฟล์ชนกัน',
  })[action] ?? action;
}

export function printWritePlan(plan) {
  finalizeWritePlan(plan);
  console.log('\nแผนการเปลี่ยนแปลง:');
  for (const entry of plan.entries) {
    console.log(`\n${actionLabel(entry.action)}: ${entry.key}`);
    if (entry.existing !== null && entry.content !== entry.existing && entry.action !== 'preserve') {
      console.log(formatLineDiff(entry.existing, entry.content));
    }
  }
  if (plan.manifestChanged) console.log(`\nอัปเดต manifest: .agent-skill-manager.json`);
}

async function resolveInteractiveConflicts(plan) {
  for (const entry of plan.entries.filter((item) => item.action === 'conflict')) {
    const choice = await select({
      message: `เลือกการจัดการไฟล์ ${entry.key}`,
      choices: [
        { name: 'อัปเดตเป็นเวอร์ชันที่สร้าง (สำรองไฟล์เดิมก่อน)', value: 'overwrite' },
        { name: 'เก็บไฟล์เดิมและข้ามรายการนี้', value: 'keep' },
        { name: 'ยกเลิกทั้งหมด', value: 'cancel' },
      ],
    });
    if (choice === 'cancel') {
      const error = new Error('ยกเลิกโดยผู้ใช้');
      error.name = 'UserCancelledError';
      throw error;
    }
    entry.action = choice;
  }
  finalizeWritePlan(plan);
}

function validateCommitPolicy(policy) {
  if (!['ask', 'auto', 'off'].includes(policy)) throw new Error('ค่า commit policy ต้องเป็น ask, auto หรือ off');
  return policy;
}

export async function setGitCommitPolicy(projectDir, policy, { yes = false, dryRun = false } = {}) {
  validateCommitPolicy(policy);
  const path = join(projectDir, PROJECT_CONFIG);
  let existing = null;
  if (existsSync(path)) {
    existing = parseProjectConfig(readFileSync(path, 'utf8'));
  }
  const oldPolicy = existing?.git?.commitPolicy ?? 'ask (ค่าเริ่มต้น)';
  console.log(`นโยบาย Git ปัจจุบัน: ${oldPolicy}`);
  console.log(`นโยบายใหม่: ${policy}`);
  if (oldPolicy === policy) {
    console.log('นโยบายนี้ถูกตั้งไว้แล้ว');
    return true;
  }
  if (dryRun) return false;
  if (!yes) {
    const accepted = await confirm({ message: 'บันทึกการเปลี่ยนแปลงนี้หรือไม่?', default: false });
    if (!accepted) return false;
  }
  const manifest = existsSync(join(projectDir, '.agent-skill-manager.json'))
    ? readProjectManifest(projectDir)
    : null;
  if (existing && existsSync(path)) backupExistingFile(projectDir, PROJECT_CONFIG, readFileSync(path, 'utf8'));
  const updated = { ...(existing ?? {}), git: { ...(existing?.git ?? {}), commitPolicy: policy } };
  const content = `${JSON.stringify(updated, null, 2)}\n`;
  writeFileSafely(projectDir, PROJECT_CONFIG, content);
  const configKey = PROJECT_CONFIG.replaceAll('\\', '/');
  if (manifest?.managedFiles?.[configKey]) {
    manifest.managedFiles[configKey] = { sha256: sha256(content) };
    writeFileSafely(projectDir, '.agent-skill-manager.json', `${JSON.stringify(manifest, null, 2)}\n`);
  }
  console.log(`บันทึกแล้ว: ${PROJECT_CONFIG}`);
  return true;
}

export async function runInteractive({
  skillsDir = SKILLS_DIR,
  outputDir = process.cwd(),
  mode: requestedMode = null,
  profile: requestedProfile = null,
  dryRun = false,
  nonInteractive = false,
  conflictPolicy = null,
  commitPolicy = null,
} = {}) {
  const rules = discoverRules(skillsDir);
  if (rules.length === 0) {
    console.error(`ไม่พบไฟล์ Markdown ใน ${skillsDir}`);
    process.exitCode = 1;
    return [];
  }

  let mode;
  let selected;
  if (nonInteractive) {
    if (!requestedMode) throw new Error('--non-interactive ต้องระบุ --mode agent หรือ --mode skill');
    mode = requestedMode;
    const profile = requestedProfile ?? 'general';
    if (profile === 'custom') throw new Error('โหมด --non-interactive ยังไม่รองรับ --profile custom ให้ใช้ profile ที่กำหนดไว้');
    selected = getProfileRules(rules, profile);
  } else {
    const startMode = requestedMode ? 'custom' : await select({
      message: 'เริ่มต้นใช้งานแบบไหน',
      choices: [
        { name: 'เริ่มงานทั่วไป (แนะนำ) — Antigravity Agent พร้อมทำงาน', value: 'recommended-agent' },
        { name: 'สร้าง Skill ทั่วไป — Antigravity Skill สำหรับโปรเจกต์', value: 'recommended-skill' },
        { name: 'ตั้งค่าเอง — สำหรับการใช้งานขั้นสูง', value: 'custom' },
      ],
    });
    if (startMode === 'recommended-agent' || startMode === 'recommended-skill') {
      mode = startMode === 'recommended-agent' ? 'agent' : 'skill';
      selected = getProfileRules(rules, 'general');
    } else {
      mode = requestedMode ?? await select({
        message: 'เลือกชนิดไฟล์ที่ต้องการสร้าง',
        choices: [
          { name: 'Agent — สร้าง custom agent ใน Antigravity', value: 'agent' },
          { name: 'Skill — สร้าง skill มาตรฐานใน Antigravity', value: 'skill' },
        ],
      });
    }

    if (!selected) {
      const profile = requestedProfile ?? await select({
        message: 'เลือกชุดการทำงาน',
        choices: [
          { name: 'ทีมพัฒนาทั่วไป — ใช้ได้กับทุกภาษาและทุก framework', value: 'general' },
          { name: 'Developer — เน้นลงมือพัฒนาและ TDD', value: 'developer' },
          { name: 'Tester / QA — เน้น test และตรวจคุณภาพ', value: 'tester' },
          { name: 'CI/CD + Git — เน้นส่งมอบและ release', value: 'delivery' },
          { name: 'เลือกกฎเอง — รวมกฎเฉพาะทางได้', value: 'custom' },
        ],
      });
    if (profile === 'custom') {
      const selectedPaths = await checkbox({
        message: 'เลือกกฎที่ต้องการใช้ (Space เลือก, Enter ยืนยัน)',
        choices: rules.map((rule) => ({ name: formatChoice(rule), value: rule.path })),
        pageSize: 15,
        required: true,
      });
      selected = rules.filter((rule) => selectedPaths.includes(rule.path));
    } else {
      selected = getProfileRules(rules, profile);
      console.log(`ใช้ชุดกฎ: ${selected.length} รายการ`);
    }
    }
  }

  if (selected.length === 0) {
    throw new Error('ไม่พบกฎของชุดที่เลือก กรุณาตรวจสอบโฟลเดอร์ skills');
  }

  const policy = conflictPolicy ?? (nonInteractive ? 'error' : 'prompt');
  const plan = planCompiledRules(selected, outputDir, mode, { conflictPolicy: policy, commitPolicy });
  printWritePlan(plan);
  if (policy === 'prompt') await resolveInteractiveConflicts(plan);
  finalizeWritePlan(plan);

  const changes = plan.entries.some((entry) => ['create', 'update', 'overwrite'].includes(entry.action)) || plan.manifestChanged;
  if (!dryRun && changes && !nonInteractive) {
    const accepted = await confirm({ message: 'ดำเนินการตามแผนนี้หรือไม่?', default: true });
    if (!accepted) {
      console.log('ยกเลิกแล้ว ไม่มีไฟล์ถูกเปลี่ยนแปลง');
      return [];
    }
  }
  const result = applyWritePlan(plan, { dryRun });
  if (dryRun) console.log('\nDry run: ไม่มีการเขียนไฟล์');
  else {
    const skipped = plan.entries.filter((entry) => ['keep', 'preserve'].includes(entry.action)).length;
    console.log(`\nเสร็จแล้ว: เขียน ${result.written.length} ไฟล์${skipped ? `, ข้าม/เก็บของเดิม ${skipped} ไฟล์` : ''}`);
    if (result.backups.length) console.log(`สำรองไฟล์เดิมไว้ที่: ${relative(outputDir, dirname(result.backups[0]))}`);
  }
  const outputs = plan.entries.map((entry) => join(outputDir, entry.relativePath));
  return outputs;
}

const HELP_TEXT = `Local Agent Skill Manager CLI\n\nUsage:\n  initskill [init options]\n  initskill init [options]\n  initskill doctor [--mode auto|agent|skill|both] [--json]\n  initskill config git-policy [ask|auto|off] [--yes] [--dry-run]\n  initskill --version\n\nInit options:\n  --mode agent|skill          Output format\n  --profile general|developer|tester|delivery\n  --skills-dir <path>         Rule library (defaults to bundled skills)\n  --output-dir <path>         Project root (defaults to current directory)\n  --dry-run                   Preview only; do not write files\n  --non-interactive           Require --mode; profile defaults to general\n  --on-conflict keep|overwrite|error\n                              Non-interactive default: error; overwrite makes backups\n  --commit-policy ask|auto|off\n  -h, --help                  Show help\n  -v, --version               Show version\n\nCommit policy: ask requests approval, auto permits safe local checkpoint commits, off disables commits.\n`;

function parseCliArgs(args) {
  const commandNames = new Set(['init', 'doctor', 'config', 'help', 'version']);
  let command = 'init';
  let index = 0;
  if (args[0] && !args[0].startsWith('-') && commandNames.has(args[0])) {
    command = args[0];
    index = 1;
  }
  const options = { _: [] };
  while (index < args.length) {
    const token = args[index++];
    if (token === '-h' || token === '--help') { options.help = true; continue; }
    if (token === '-v' || token === '--version') { options.version = true; continue; }
    if (token === '--dry-run') { options.dryRun = true; continue; }
    if (token === '--non-interactive') { options.nonInteractive = true; continue; }
    if (token === '--json') { options.json = true; continue; }
    if (token === '--yes') { options.yes = true; continue; }
    if (!token.startsWith('--')) { options._.push(token); continue; }
    const [rawName, inlineValue] = token.slice(2).split(/=(.*)/s, 2);
    const key = rawName.replaceAll('-', '');
    if (!['mode', 'profile', 'skillsdir', 'outputdir', 'onconflict', 'commitpolicy'].includes(key)) {
      throw new Error(`ไม่รู้จัก option: --${rawName}`);
    }
    const value = inlineValue ?? args[index++];
    if (!value || value.startsWith('--')) throw new Error(`ขาดค่าของ ${token}`);
    options[key] = value;
  }
  return { command, options };
}

function showVersion() {
  const packageInfo = JSON.parse(readFileSync(join(ROOT, 'package.json'), 'utf8'));
  console.log(packageInfo.version);
}

async function main(args) {
  if (Number(process.versions.node.split('.')[0]) < 20) {
    throw new Error(`ต้องใช้ Node.js 20 ขึ้นไป (ปัจจุบัน ${process.versions.node})`);
  }
  const { command, options } = parseCliArgs(args);
  if (options.help || command === 'help') { console.log(HELP_TEXT); return; }
  if (options.version || command === 'version') { showVersion(); return; }
  const outputDir = resolve(options.outputdir ?? process.cwd());

  if (command === 'doctor') {
    if (options._.length) throw new Error(`doctor ไม่รองรับ argument: ${options._.join(' ')}`);
    const mode = options.mode ?? 'auto';
    runDoctor(outputDir, { mode, json: options.json });
    return;
  }
  if (command === 'config') {
    if (options._[0] !== 'git-policy') throw new Error('ใช้: initskill config git-policy [ask|auto|off]');
    const policy = options._[1];
    if (!policy) {
      const path = join(outputDir, PROJECT_CONFIG);
      const value = existsSync(path) ? parseProjectConfig(readFileSync(path, 'utf8'))?.git?.commitPolicy ?? 'ask' : 'ask';
      console.log(`Git commit policy: ${value}`);
      return;
    }
    await setGitCommitPolicy(outputDir, policy, { yes: options.yes, dryRun: options.dryRun });
    return;
  }
  if (!['init'].includes(command)) throw new Error(`ไม่รู้จักคำสั่ง: ${command}`);
  if (options._.length) throw new Error(`ไม่รู้จักคำสั่งหรือ argument: ${options._.join(' ')}`);
  if (options.mode && !['agent', 'skill'].includes(options.mode)) throw new Error('--mode ต้องเป็น agent หรือ skill');
  if (options.profile && !['general', 'developer', 'tester', 'delivery', 'custom'].includes(options.profile)) {
    throw new Error('--profile ต้องเป็น general, developer, tester, delivery หรือ custom');
  }
  if (options.commitpolicy) validateCommitPolicy(options.commitpolicy);
  if (options.onconflict && !['keep', 'overwrite', 'error'].includes(options.onconflict)) {
    throw new Error('--on-conflict ต้องเป็น keep, overwrite หรือ error');
  }
  await runInteractive({
    skillsDir: resolve(options.skillsdir ?? SKILLS_DIR),
    outputDir,
    mode: options.mode ?? null,
    profile: options.profile ?? null,
    dryRun: options.dryRun ?? false,
    nonInteractive: options.nonInteractive ?? false,
    conflictPolicy: options.onconflict ?? null,
    commitPolicy: options.commitpolicy ?? null,
  });
}

if (process.argv[1] && resolve(process.argv[1]) === resolve(fileURLToPath(import.meta.url))) {
  main(process.argv.slice(2)).catch((error) => {
    if (error.name === 'ExitPromptError' || error.name === 'UserCancelledError') {
      console.log('\nยกเลิกการทำงาน');
      process.exitCode = 130;
    } else {
      console.error(`ผิดพลาด: ${error.message}`);
      process.exitCode = error.message.startsWith('ไฟล์มีอยู่แล้ว') ? 3 : 1;
    }
  });
}
