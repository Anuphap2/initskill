export function detectProject(projectDir = process.cwd()) {
  const markers = [
    ['package.json', 'Node.js / JavaScript / TypeScript'],
    ['pyproject.toml', 'Python'],
    ['requirements.txt', 'Python'],
    ['go.mod', 'Go'],
    ['Cargo.toml', 'Rust'],
    ['pom.xml', 'Java / Maven'],
    ['build.gradle', 'Java / Gradle'],
    ['Gemfile', 'Ruby'],
    ['composer.json', 'PHP'],
  ];
  const stacks = markers.filter(([file]) => existsSync(join(projectDir, file))).map(([, stack]) => stack);
  const packagePath = join(projectDir, 'package.json');
  let packageInfo = null;
  if (existsSync(packagePath)) {
    try { packageInfo = JSON.parse(readFileSync(packagePath, 'utf8')); } catch { packageInfo = null; }
  }
  const lockfiles = ['package-lock.json', 'pnpm-lock.yaml', 'yarn.lock', 'bun.lockb']
    .filter((file) => existsSync(join(projectDir, file)));
  return {
    stacks: [...new Set(stacks)],
    packageManager: lockfiles[0] ?? null,
    packageName: packageInfo?.name ?? null,
    scripts: packageInfo?.scripts ? Object.keys(packageInfo.scripts) : [],
  };
}

