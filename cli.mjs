function ruleKey(rule) {
  return rule.relativePath.replaceAll('\\', '/').toLowerCase();
}

export function getProfileRules(rules, profile = 'general') {
  if (!PROFILES[profile]) throw new Error(`ไม่รู้จักชุดงาน: ${profile}`);
  const wanted = new Set(PROFILES[profile]);
  return rules.filter((rule) => wanted.has(ruleKey(rule)));
}

function getRulesByKeys(rules, keys) {
  const wanted = new Set(keys);
  return rules.filter((rule) => wanted.has(ruleKey(rule)));
}

function walkMarkdown(directory) {
  if (!existsSync(directory)) return [];
  const entries = readdirSync(directory, { withFileTypes: true });
  return entries.flatMap((entry) => {
    const absolutePath = join(directory, entry.name);
    if (entry.isDirectory()) return walkMarkdown(absolutePath);
    return entry.isFile() && extname(entry.name).toLowerCase() === '.md' ? [absolutePath] : [];
  }).sort((a, b) => a.localeCompare(b));
}

function parseRule(filePath, skillsDir = SKILLS_DIR) {
  const content = readFileSync(filePath, 'utf8').trim();
  const titleMatch = content.match(/^#\s+(.+?)\s*$/m);
  const category = relative(skillsDir, dirname(filePath)).split(/[/\\]/)[0] || 'uncategorized';
  return {
    path: filePath,
    relativePath: relative(skillsDir, filePath),
    title: titleMatch?.[1] ?? filePath.split(/[/\\]/).pop().replace(/\.md$/i, ''),
    category,
    content,
  };
}

export function discoverRules(skillsDir = SKILLS_DIR) {
  return walkMarkdown(skillsDir).map((filePath) => parseRule(filePath, skillsDir));
}

export function compileRules(rules, { generatedAt = false } = {}) {
  if (rules.length === 0) throw new Error('เลือกกฎอย่างน้อย 1 รายการ');
  const header = generatedAt
    ? `<!-- Generated by Local Agent Skill Manager on ${new Date().toISOString()} -->\n\n`
    : '<!-- Generated by Local Agent Skill Manager -->\n\n';
  const sections = rules.map((rule) => [
    `## ${rule.title}`,
    `<!-- source: ${rule.relativePath} | category: ${rule.category} -->`,
    rule.content.replace(/^#\s+.+?\s*$/m, '').trim(),
  ].join('\n\n'));
  return header + sections.join('\n\n---\n\n') + '\n';
}

